//! The UNIFIED spec catalog crate — every algorithm family the default
//! `array_vis_bench` binary shows, GATHERED from per-crate catalog fragments.
//!
//! Each building-stone family crate OWNS its catalog fragment + query and points
//! at them from its manifest (`[package.metadata.array_vis_bench] spec/query`).
//! `build.rs` runs `cargo metadata`, walks this crate's dependency closure, reads
//! every gathered `spec` fragment into ONE `spec_core` registry, lowers + solves
//! each `query` independently (`spec_core::avbs`), and emits one `mod __entry_N`
//! per solved variant via `spec_emit::ArrayBackend` — registering an
//! `AlgorithmEntry` into the real `array_vis_bench_core::bench_registry::ALGORITHMS`
//! and a picker variant into `sort_registry_core`. Today's families: shell (18),
//! insertion (2), quick (408 — the slotted port). These are the CANONICAL
//! registrations (no `spec::` marker); leaf crates are linked for their types.
//!
//! This is the user's two-layer model, "B" stage: building stones are
//! self-describing Rust crates (Layer 1, each carrying its own `.spec`/`.avbs`);
//! this crate is the query layer (Layer 2) that imports them all and gathers +
//! emits. Adding a family = give its crate a `spec`/`query` block + a dep here.

// @generated by build.rs (spec_core::emit_entries + spec_emit::ArrayBackend):
// one self-contained `mod __entry_N` per variant across ALL families. Each
// module's `use <leaf>::…;` links the building-stone crate for its types.
include!(concat!(env!("OUT_DIR"), "/catalog_entries.rs"));

// @generated by build.rs: `run_declared_consumers()` + `DECLARED_CONSUMER_SHAPE`,
// the catalog's `consumers.avbs` (`consumers: List<Mains<Set>>`) resolved to
// concrete (main, algorithm labels). The binary's `--consumers` mode runs this —
// the language's consumer surface as the app's main, over the real catalog.
include!(concat!(env!("OUT_DIR"), "/declared_consumers.rs"));

/// Run the named consumer Mains (e.g. `["correctness", "benchmark"]`) over the
/// ENTIRE emitted catalog — every linked `AlgorithmEntry`, all kinds. This is the
/// faithful "all" set: the emitted catalog itself, not a query re-derivation
/// (a wildcard like `SortingAlgorithm<_>` would re-enumerate role `Sort` WITHOUT
/// each family's arity coupling/curation and produce labels that don't match what
/// was emitted). One [`array_vis_bench_core::mains::MainReport`] per Main.
pub fn run_over_catalog(
    main_names: &[&str],
) -> Result<Vec<array_vis_bench_core::mains::MainReport>, String> {
    use array_vis_bench_core::bench_registry::{AlgorithmEntry, ALGORITHMS};
    use array_vis_bench_core::mains::{main_by_name, run_all, Main};

    let consumers: Vec<Box<dyn Main>> = main_names
        .iter()
        .map(|n| main_by_name(n).ok_or_else(|| format!("unknown consumer `{n}`")))
        .collect::<Result<_, _>>()?;
    let all: Vec<&'static AlgorithmEntry> = ALGORITHMS.iter().collect();
    let refs: Vec<&dyn Main> = consumers.iter().map(|b| b.as_ref()).collect();
    Ok(run_all(&refs, &all))
}

/// Time every registered SORT on a random array of size `n`, `k` times each,
/// and print the 10 fastest + 10 slowest by median run time (see
/// [`array_vis_bench_core::mains::Timing`]). Runs over the `Category::Sort`
/// slice of the emitted catalog — the "sorts we're looking at" — so the ranking
/// compares like with like (a merge/rotation step isn't a full sort).
pub fn run_timing(n: usize, k: usize) -> array_vis_bench_core::mains::MainReport {
    use array_vis_bench_core::bench_registry::{Category, AlgorithmEntry, ALGORITHMS};
    use array_vis_bench_core::mains::{Main, Timing};
    let sorts: Vec<&'static AlgorithmEntry> =
        ALGORITHMS.iter().filter(|e| e.category == Category::Sort).collect();
    Timing { n, k }.run(&sorts)
}

