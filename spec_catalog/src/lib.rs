                    assert_eq!(e.best, <$ty as HasTimeBounds>::BEST, "best: {}", $name);
                    assert_eq!(e.average, <$ty as HasTimeBounds>::AVERAGE, "average: {}", $name);
                    assert_eq!(e.space, <$ty as HasSpace>::SPACE, "space: {}", $name);
