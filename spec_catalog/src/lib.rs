        /// End-to-end through the `Main` consumer abstraction.
        #[test]
        fn shells_tick_through_the_consumers() {
            use array_vis_bench_core::mains::{run_all, Benchmark, Correctness, Main, Visualiser};

            let sorts = entries();
            let correctness = Correctness;
            let visualiser = Visualiser::default();
            let benchmark = Benchmark::default();
            let consumers: Vec<&dyn Main> = vec![&correctness, &visualiser, &benchmark];

            let reports = run_all(&consumers, &sorts);
            assert_eq!(reports.len(), 3);
            for rep in &reports {
                assert_eq!(rep.ran, 18, "{} ran {} of 18", rep.consumer, rep.ran);
                assert!(rep.all_ok(), "{} had failures: {:?}", rep.consumer, rep.failures);
                assert_eq!(rep.ok, 18, "{} ok {} of 18", rep.consumer, rep.ok);
            }
        }

        /// THE CLOSED LOOP from the AVBS *language* surface: a `consumers:` program
        /// over the unified `catalog.spec`, lowered → resolved → run via the real
        /// `Main` impls over the matching registered entries.
        #[test]
        fn consumers_binding_drives_the_mains_end_to_end() {
            use array_vis_bench_core::mains::run_named;

            // The merged registry, dumped by build.rs from the gathered fragments.
            let reg = spec_core::Registry::parse(include_str!(concat!(
                env!("OUT_DIR"),
                "/merged_catalog.spec"
            )))
            .expect("parse merged catalog");
            let program = spec_core::avbs::lower(
                r#"
                ShellSorts:        SortingAlgorithm = SortingAlgorithm<ShellSort<_>>
                ShellSortsOrdered: SortingAlgorithm = SortingAlgorithm<ShellSortOrdered<_>>
                Sorts:             List<SortingAlgorithm> = [ShellSorts, ShellSortsOrdered]
                consumers:         List<Mains<Sorts>> = [visualiser, correctness, benchmark]
                "#,
                &reg,
            )
            .expect("lower the consumers program");

            let resolved = program.resolve_consumers(&reg).expect("resolve consumers");
            assert_eq!(resolved.len(), 1);
            let consumer = &resolved[0];
            // `Sorts` = plain ∪ ordered = all 18 shells.
            assert_eq!(consumer.algo_labels.len(), 18);

            let mains: Vec<&str> = consumer.mains.iter().map(String::as_str).collect();
            let labels: Vec<&str> = consumer.algo_labels.iter().map(String::as_str).collect();
            let reports = run_named(&mains, &labels).expect("all consumer names are known");

            assert_eq!(reports.len(), 3, "visualiser + correctness + benchmark");
            for rep in &reports {
                assert_eq!(rep.ran, 18, "{} ran {} of 18", rep.consumer, rep.ran);
                assert!(rep.all_ok(), "{} had failures: {:?}", rep.consumer, rep.failures);
                assert_eq!(rep.ok, 18, "{} ok {} of 18", rep.consumer, rep.ok);
            }
        }

